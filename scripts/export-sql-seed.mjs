#!/usr/bin/env node
// Generates supabase/seed.sql from src/data/dataset.json so the Postgres database
// starts from exactly the data the site renders today.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const d = JSON.parse(fs.readFileSync(path.join(root, "src/data/dataset.json"), "utf8"));

const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(",")}]::text[]` : "'{}'::text[]";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const rows = [];
const insert = (table, objs, cols) => {
  if (!objs.length) return;
  rows.push(`insert into ${table} (${cols.join(", ")}) values\n` +
    objs.map((o) => `  (${cols.map((c) => lit(typeof c === "string" ? o[c] : null)).join(", ")})`).join(",\n") + ";\n");
};

const f = d.franchise;
insert("franchise", [f], ["id", "current_name", "original_name", "earliest_verified_season_id", "home_complex", "notes"]);
insert("eras", d.eras.map((e) => ({ ...e, franchise_id: f.id })),
  ["id", "franchise_id", "name", "display_name", "first_season_id", "last_season_id", "start_note", "end_note", "logo_treatment", "notes"]);
insert("source_evidence", d.source_evidence.map((e) => ({ ...e, file_path: e.file })),
  ["id", "kind", "title", "file_path", "public_url", "coverage", "confidence"]);
insert("seasons", d.seasons, ["id", "slug", "era_id", "year", "session", "sort_key", "team_name_at_time", "league", "division",
  "league_size", "regular_wins", "regular_losses", "regular_ties", "regular_place", "postseason_wins", "postseason_losses",
  "overall_wins", "overall_losses", "overall_ties", "overall_source", "playoff_finish", "playoff_finish_code", "champion",
  "title_under_review", "undefeated", "confidence", "regular_confidence", "postseason_confidence", "championship_note",
  "postseason_note", "regular_season_note", "source_notes", "schedule_revision", "playoff_revision"]);
insert("season_sources", d.seasons.flatMap((s) => s.source_evidence_ids.map((id) => ({ season_id: s.id, source_evidence_id: id }))),
  ["season_id", "source_evidence_id"]);
insert("opponents", d.opponents, ["id", "slug", "canonical_name", "aliases"]);
insert("standings", d.standings, ["season_id", "place", "team", "is_franchise", "opponent_id", "w", "l", "t", "gb", "gp", "pct", "streak", "coach"]);
insert("games", d.games, ["id", "slug", "season_id", "date", "time", "field", "opponent_id", "home_away", "team_score", "opponent_score",
  "result", "status", "stage", "week", "playoff_round", "playoff_round_label", "bracket_game", "is_title_game", "team_name_at_time",
  "confidence", "source_evidence_id", "notes"]);
insert("league_games", d.league_games, ["season_id", "date", "time", "field", "stage", "week", "round", "round_label", "bracket_game",
  "away", "home", "away_score", "home_score", "away_result", "home_result", "status", "notes"]);
insert("players", d.players.map((p) => ({ ...p, id: p.slug })), ["id", "slug", "name", "short_name", "number", "positions", "active", "photo", "bio", "confidence", "source"]);
insert("season_rosters", d.season_rosters.map((r) => ({ ...r, player_id: r.player_slug })), ["season_id", "player_id", "number", "positions", "confidence"]);
insert("plate_appearances", d.plate_appearances.map((p) => ({ ...p, player_id: p.player_slug })),
  ["game_id", "player_id", "pa_index", "inning", "result", "rbi", "run_scored", "notes"]);
insert("championships", d.championships, ["id", "slug", "season_id", "title", "team_name_at_time", "confidence", "verification",
  "undefeated", "title_game_id", "evidence_image", "notes"]);
insert("review_queue", d.review_queue, ["id", "entity", "entity_id", "severity", "message"]);

const out = `-- Generated by scripts/export-sql-seed.mjs from src/data/dataset.json (${d.meta.built_at}). Do not edit by hand.\nbegin;\n${rows.join("\n")}commit;\n`;
fs.writeFileSync(path.join(root, "supabase/seed.sql"), out);
console.log(`supabase/seed.sql written (${(out.length / 1024).toFixed(0)} KB)`);
